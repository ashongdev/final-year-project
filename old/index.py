def validate_requirements():
    """
    Validate that all required files and configurations exist before processing.
    Returns tuple: (is_valid: bool, error_messages: list)
    """
    errors = []

    # Check environment variables
    if not SHEET_ID:
        errors.append("SHEET_ID environment variable is not set")
    if not GOOGLE_API_KEY:
        errors.append("GOOGLE_API_KEY environment variable is not set")

    # Check service account file
    service_account_file = "./service_account.json"
    if not os.path.exists(service_account_file):
        errors.append(f"Service account file not found: {service_account_file}")

    # Check font file
    font_file = "arialbd.ttf"
    if not os.path.exists(font_file):
        errors.append(f"Font file not found: {font_file}")

    # Check templates directory structure
    templates_dir = "templates"
    if not os.path.exists(templates_dir):
        errors.append(f"Templates directory not found: {templates_dir}")
    else:
        # Check each competition template
        for comp_code, comp_name in comps.items():
            comp_dir = os.path.join(templates_dir, comp_name)
            if not os.path.exists(comp_dir):
                errors.append(f"Competition template directory not found: {comp_dir}")
                continue

            # Check position templates
            for pos_num, position in positions.items():
                position_formatted = position.replace("-", "_")
                template_file = os.path.join(
                    comp_dir, f"{comp_name}_{position_formatted}.png"
                )
                if not os.path.exists(template_file):
                    errors.append(f"Template file not found: {template_file}")

    return len(errors) == 0, errors


